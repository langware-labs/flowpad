"""Generate client role contracts from the hub's canonical registry.

Usage: python scripts/generate_roles.py /path/to/hub/flowpad/enums/auth_enums.py
"""

import json
import runpy
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
registry = runpy.run_path(str(source))
order = registry["ROLE_ORDER"]
header = "# Generated by scripts/generate_roles.py from hub flowpad/enums/auth_enums.py.\n"
python = header + source.read_text() + "\n\nclass HubRole(StrEnum):\n"
python += "".join(f"    {role.upper()} = {role!r}\n" for role in order)
python += "\n\nVISITOR_AUTH_ROLE = AuthRole.READER\n"
(root / "flow_sdk/flowpad_types/enums/auth_enums.py").write_text(python)
ts = "// Generated by scripts/generate_roles.py from hub flowpad/enums/auth_enums.py.\n"
ts += "export const ROLE_ORDER = " + json.dumps(order) + " as const;\n"
ts += "export const Role = " + json.dumps({role.upper(): role for role in order}) + " as const;\n"
ts += (
    "export const ROLE_PEER_INVITE_TYPES: readonly string[] = "
    + json.dumps(sorted(registry["ROLE_PEER_INVITE_TYPES"]))
    + ";\n"
)
ts += "export type Role = (typeof ROLE_ORDER)[number];\n"
ts += (
    "export const MEMBERSHIP_ROLES: readonly Role[] = "
    + json.dumps([r for r in order if r in registry["MEMBERSHIP_ROLES"]])
    + ";\n"
)
for name in ("ROLE_INCLUDES", "ROLE_GRANTS"):
    data = {role: [r for r in order if r in registry[name][role]] for role in order}
    ts += f"export const {name}: Record<Role, readonly Role[]> = " + json.dumps(data, indent=2) + ";\n"
ts += """
export function normalizeRoles(value: readonly string[] | string | null | undefined): Role[] {
  const roles = (typeof value === 'string' ? [value] : value ?? []).map(role => {
    if (typeof role !== 'string') throw new Error('Roles must contain strings');
    return role.trim().toLowerCase();
  });
  for (const role of roles) {
    if (!(ROLE_ORDER as readonly string[]).includes(role)) throw new Error(`Unknown role: ${role}`);
  }
  return ROLE_ORDER.filter(role => roles.includes(role));
}
export function normalizeMembershipRoles(value: readonly string[] | string | null | undefined): Role[] {
  const roles = normalizeRoles(value);
  if (roles.some(role => !MEMBERSHIP_ROLES.includes(role))) throw new Error('Unassignable membership role');
  return roles;
}
export function normalizeRetainedRoles(value: readonly string[] | null | undefined): Role[] {
  const roles = normalizeMembershipRoles(value);
  if (roles.some(role => !ROLE_GRANTS.owner.includes(role))) throw new Error('Unassignable retained role');
  return roles;
}
export function roleCapabilities(value: readonly string[]): Set<Role> {
  return new Set(normalizeRoles(value).flatMap(role => ROLE_INCLUDES[role]));
}
export function grantableRoleSet(value: readonly string[]): Role[] {
  const granted = new Set(normalizeRoles(value).flatMap(role => ROLE_GRANTS[role]));
  return ROLE_ORDER.filter(role => granted.has(role));
}
export function newInviteRoles(held: readonly string[], entityType: string): Role[] {
  const grants = grantableRoleSet(held);
  if (grants.length || !ROLE_PEER_INVITE_TYPES.includes(entityType)) return grants;
  const capabilities = roleCapabilities(held);
  return ROLE_ORDER.filter(role => (role === 'reader' || role === 'runner') && capabilities.has(role));
}
export function canManageRoles(held: readonly string[], target: readonly string[]): boolean {
  const grants = grantableRoleSet(held);
  return target.length > 0 && normalizeRoles(target).every(role => grants.includes(role));
}
"""
(root / "ts_sdk/src/models/roles.ts").write_text(ts)
